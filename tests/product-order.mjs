import assert from 'node:assert/strict';
import { build } from 'esbuild';
const result = await build({ stdin: { contents: `export * from './lib/catalog'; export * from './lib/cart'; export * from './lib/admin-validation';`, resolveDir: process.cwd() }, bundle: true, platform: 'node', format: 'esm', define: { 'import.meta.env.DEV': 'true' }, write: false });
const memory = new Map();
globalThis.localStorage = { getItem: key => memory.get(key) ?? null, setItem: (key, value) => memory.set(key, value) };
globalThis.window = { dispatchEvent() {} };
const { defaultCatalog, stockLabel, validResource, saveCatalog, readCart, addToCart, changeCartQuantity, changeCartSize, submitOrder } = await import(`data:text/javascript;base64,${Buffer.from(result.outputFiles[0].text).toString('base64')}`);
const product = defaultCatalog[0];
assert.equal(stockLabel(undefined), 'In stock');
assert.equal(validResource('catalog', [{ ...product, stockStatus: undefined }]), true, 'legacy products work');
for (const stockStatus of ['in_stock', 'out_of_stock', 'preorder']) assert.equal(validResource('catalog', [{ ...product, stockStatus }]), true);
assert.equal(validResource('catalog', [{ ...product, stockStatus: 'unknown' }]), false);
saveCatalog([{ ...product, stockStatus: 'out_of_stock' }]);
addToCart(product);
assert.equal(readCart().length, 0, 'stale detail page cannot add out of stock product');
saveCatalog([{ ...product, stockStatus: 'preorder' }]);
addToCart({ ...product, stockStatus: 'preorder' }, "S");
assert.equal(readCart().length, 1, 'preorder can be ordered');
saveCatalog([{ ...product, stockStatus: 'out_of_stock' }]);
const customer = { customer: 'Test customer', phone: '09000000000', address: 'Test address' };
await assert.rejects(submitOrder(customer), /out of stock/);
assert.equal(readCart().length, 1, 'failed order retains cart');
assert.equal(memory.has('uksein_orders'), false, 'failed order is not recorded');
saveCatalog([{ ...product, stockStatus: 'in_stock' }]);
const order = await submitOrder(customer);
assert.equal(order.phone, customer.phone);
assert.equal(readCart().length, 0, 'successful order clears cart');
assert.equal(JSON.parse(memory.get('uksein_orders'))[0].id, order.id, 'receipt references saved order');
assert.match(order.item, / · S × 1/, 'order details include chosen size');
assert.throws(() => addToCart(product), /choose an available size/, 'size is required');
assert.throws(() => addToCart(product, 'XL'), /choose an available size/, 'reject sizes not sold');
addToCart(product, 'S'); addToCart(product, 'M'); addToCart(product, 'S');
assert.equal(readCart().length, 2, 'different sizes remain separate cart lines');
assert.equal(readCart().find(line => line.size === 'S').quantity, 2, 'matching sizes combine');
const medium = readCart().find(line => line.size === 'M');
changeCartQuantity(medium.id, 4);
assert.equal(readCart().find(line => line.size === 'S').quantity, 2, 'quantity edits do not affect another size');
changeCartSize(readCart().find(line => line.size === 'S').id, 'M');
assert.equal(readCart().length, 1, 'changing to an existing size merges lines');
assert.equal(readCart()[0].quantity, 6, 'merging preserves quantities');
saveCatalog([{ ...product, sizes: ['S'] }]);
await assert.rejects(submitOrder(customer), /choose an available size/, 'recheck size availability at checkout');
assert.equal(readCart().length, 1, 'invalid size retains cart');
saveCatalog([product]);
memory.set('uksein_cart', JSON.stringify([{ id: product.id, name: product.name, price: product.price, image: product.image, quantity: 1 }]));
await assert.rejects(submitOrder(customer), /choose an available size/, 'legacy cart asks for a size');
changeCartSize(product.id, 'L');
const legacyOrder = await submitOrder(customer);
assert.match(legacyOrder.item, / · L × 1/, 'legacy cart can choose a size and order');
assert.equal(order.items[0].productId, product.id);
assert.equal(order.items[0].size, 'S');
assert.equal(order.items[0].image, product.image);
assert.equal(validResource('orders', [order]), true, 'server accepts item image snapshots');
assert.equal(validResource('orders', [{ ...order, items: [{ ...order.items[0], image: 'javascript:bad' }] }]), false);
assert.equal(validResource('orders', [{ ...order, items: [{ ...order.items[0], quantity: 0 }] }]), false);
assert.equal(validResource('catalog', [{ ...product, images: Array(4).fill('https://example.com/photo.jpg') }]), true, 'cover plus four gallery photos accepted');
assert.equal(validResource('catalog', [{ ...product, images: Array(5).fill('https://example.com/photo.jpg') }]), false, 'reject sixth product photo');
assert.equal(validResource('catalog', [{ ...product, images: ['javascript:bad'] }]), false);
console.log('Stock status, sizes, product gallery and order image checks passed.');
